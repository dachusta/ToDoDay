import { version } from '../../package.json'

/**
 * Сведения для блока «О приложении» (вайрфреймы §8):
 *
 * - версия приходит из сборки. `build.define.__APP_VERSION__` в quasar.config.ts
 *   вычисляется из git (`scripts/app-version.mjs`): ближайший тег `vX.Y.Z` плюс
 *   смещение от него — `0.1.0`, `0.1.0+3.g01a2e03`, `0.1.0+3.g01a2e03.dirty`.
 *   Второго места для номера версии по-прежнему нет: `package.json` остаётся
 *   базой на случай, когда тегов в истории ещё нет (README, «Версия сборки»);
 * - в тестах и в редакторе глобала нет — `define` подставляет только сборка, —
 *   поэтому подставляется `version` из `package.json`: экран показывает то же
 *   значение, что и проверяет `test/components/settingsPage.spec.ts`;
 * - дата сборки — константа релиза. Сборка её не подставляет: в вайрфреймах это
 *   дата выпуска, а не время запуска `quasar build`, и `new Date()` на экране
 *   показывал бы дату открытия настроек, а не дату выпуска. Константа меняется
 *   вместе с тегом версии — порядок в README, «Версия сборки».
 */
export const APP_VERSION: string =
  typeof __APP_VERSION__ === 'undefined' ? version : __APP_VERSION__

/** Дата сборки 'YYYY-MM-DD' — строка «Сборка» блока «О приложении». */
export const APP_BUILD_DATE = '2026-10-09'
